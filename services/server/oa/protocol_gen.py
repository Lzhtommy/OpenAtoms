"""Generate TypeScript protocol types from oa.protocol. Usage: python -m oa.protocol_gen <out.ts>"""
from __future__ import annotations

import json
import sys
from enum import Enum
from pathlib import Path

from oa import protocol


def render() -> str:
    out = ["// AUTO-GENERATED by `make protocol` from services/server/oa/protocol.py — do not edit.", ""]
    for name in dir(protocol):
        obj = getattr(protocol, name)
        if isinstance(obj, type) and issubclass(obj, Enum) and obj.__module__ == protocol.__name__:
            values = [m.value for m in obj]
            out.append(f"export const {name}Values = {json.dumps(values)} as const;")
            out.append(f"export type {name} = (typeof {name}Values)[number];")
            out.append("export const " + name + " = {")
            out += [f"  {m.name}: {json.dumps(m.value)}," for m in obj]
            out.append("} as const;")
            out.append("")
    out.append(f"export const SOCKET_EVENTS = {json.dumps(protocol.SOCKET_EVENTS)} as const;")
    out.append("export type SocketEvent = (typeof SOCKET_EVENTS)[number];")
    out.append(f"export const AGENTS: Record<string, string> = {json.dumps(protocol.AGENTS)};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    target = Path(sys.argv[1] if len(sys.argv) > 1 else "../../packages/protocol/src/generated.ts")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render())
    print(f"wrote {target}")
