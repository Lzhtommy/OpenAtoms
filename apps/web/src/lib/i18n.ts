export type DictKey = keyof (typeof dict)["zh"];

interface LangState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useLang = create<LangState>((set) => ({
  lang: "zh",
  setLang: (lang) => {
    if (typeof window !== "undefined") localStorage.setItem("oa_lang", lang);
    set({ lang });
  },
}));

export function initLang() {
  if (typeof window === "undefined") return;
  const l = localStorage.getItem("oa_lang");
  if (l === "en" || l === "zh") useLang.setState({ lang: l });
}

export function useT() {
  const lang = useLang((s) => s.lang);
  return (k: DictKey, vars?: Record<string, string>) => {
    let s: string = dict[lang][k] ?? k;
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, b);
    return s;
  };
}
